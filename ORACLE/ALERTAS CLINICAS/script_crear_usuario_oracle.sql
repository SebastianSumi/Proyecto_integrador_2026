-- 5. CREAR TABLA ALERTA_CLINICA
-- =====================================================
CREATE TABLE ALERTA_CLINICA (
    ID_ALERTA RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    ID_PERSONA NUMBER(10) NOT NULL,
    ID_EVALUACION_ORIGEN NUMBER(10),
    NIVEL_SEVERIDAD VARCHAR2(20) NOT NULL,
    SCORE_RIESGO NUMBER(5),
    ESTADO VARCHAR2(20) NOT NULL,
    SNAPSHOT_INMUTABLE CLOB,
    FECHA_GENERACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FECHA_VENCIMIENTO_SLA TIMESTAMP,
    VERSION NUMBER(10) DEFAULT 0,
    CONSTRAINT FK_ALERTA_PERSONA FOREIGN KEY (ID_PERSONA) REFERENCES PERSONA(ID_PERSONA),
    CONSTRAINT CK_ALERTA_SEVERIDAD CHECK (NIVEL_SEVERIDAD IN ('LEVE', 'MODERADO', 'CRITICO')),
    CONSTRAINT CK_ALERTA_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'EN_REVISION', 'ATENDIDA', 'DESESTIMADA', 'VENCIDO'))
);

-- Índices
CREATE INDEX IDX_ALERTA_PERSONA_ESTADO ON ALERTA_CLINICA(ID_PERSONA, ESTADO);
CREATE INDEX IDX_ALERTA_FECHA_VENCIMIENTO ON ALERTA_CLINICA(FECHA_VENCIMIENTO_SLA);
