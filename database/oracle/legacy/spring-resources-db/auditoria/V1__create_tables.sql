    DIRECCION_IP VARCHAR2(45) NOT NULL,
    CIUDAD VARCHAR2(100),
    PAIS VARCHAR2(100),
    CODIGO_PAIS VARCHAR2(5),
    LATITUD BINARY_DOUBLE,
    LONGITUD BINARY_DOUBLE,
