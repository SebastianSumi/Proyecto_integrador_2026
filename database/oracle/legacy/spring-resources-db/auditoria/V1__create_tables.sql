-- =====================================================
-- TABLA: BITACORA_TRANSACCIONAL
-- Particionada por rango mensual. Solo INSERT (WORM).
-- =====================================================
CREATE TABLE BITACORA_TRANSACCIONAL (
    ID_BITACORA RAW(16) DEFAULT SYS_GUID() NOT NULL,
    SECUENCIA NUMBER(19) NOT NULL,
    TIPO_EVENTO VARCHAR2(80) NOT NULL,
    ENTIDAD_AFECTADA VARCHAR2(50) NOT NULL,
    ID_ENTIDAD VARCHAR2(100) NOT NULL,
    TIPO_OPERACION VARCHAR2(20) NOT NULL,
    ID_PERSONA NUMBER(10),
    USUARIO_AUTOR VARCHAR2(100) NOT NULL,
    ROL_USUARIO VARCHAR2(100),
    TENANT_ID VARCHAR2(50),
    DIFERENCIAL_CAMBIOS CLOB,
    SNAPSHOT_ANTERIOR CLOB,
    SNAPSHOT_POSTERIOR CLOB,
    DIRECCION_IP VARCHAR2(45),
    PUERTO_REMOTO VARCHAR2(10),
    USER_AGENT VARCHAR2(255),
    ENDPOINT_HTTP VARCHAR2(200),
    METODO_HTTP VARCHAR2(10),
    CODIGO_RESPUESTA_HTTP NUMBER(3),
    HASH_REGISTRO VARCHAR2(64) NOT NULL,
    HASH_ANTERIOR VARCHAR2(64),
    FUERA_HORARIO_LABORAL VARCHAR2(1),
    FECHA_REGISTRO TIMESTAMP NOT NULL,
    CONSTRAINT PK_BITACORA_TRANSACCIONAL PRIMARY KEY (ID_BITACORA, FECHA_REGISTRO),
    CONSTRAINT CK_BITACORA_FUERA_HORARIO CHECK (FUERA_HORARIO_LABORAL IN ('S', 'N'))
)
PARTITION BY RANGE (FECHA_REGISTRO)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_INICIAL VALUES LESS THAN (TO_DATE('2026-01-01', 'YYYY-MM-DD'))
);

CREATE UNIQUE INDEX IDX_BITACORA_SECUENCIA ON BITACORA_TRANSACCIONAL(SECUENCIA);
CREATE INDEX IDX_BITACORA_ENTIDAD ON BITACORA_TRANSACCIONAL(ENTIDAD_AFECTADA, ID_ENTIDAD) LOCAL;
CREATE INDEX IDX_BITACORA_HASH_ANT ON BITACORA_TRANSACCIONAL(HASH_ANTERIOR) LOCAL;
CREATE INDEX IDX_BITACORA_USUARIO ON BITACORA_TRANSACCIONAL(USUARIO_AUTOR) LOCAL;
CREATE INDEX IDX_BITACORA_PERSONA ON BITACORA_TRANSACCIONAL(ID_PERSONA) LOCAL;

-- =====================================================
-- TABLA: BITACORA_LECTURA
-- Particionada por rango mensual.
-- =====================================================
CREATE TABLE BITACORA_LECTURA (
    ID_LECTURA RAW(16) DEFAULT SYS_GUID() NOT NULL,
    ID_PERSONA NUMBER(10) NOT NULL,
    TIPO_ENTIDAD VARCHAR2(50) NOT NULL,
    ID_ENTIDAD VARCHAR2(100) NOT NULL,
    USUARIO_LECTOR VARCHAR2(100) NOT NULL,
    DIRECCION_IP VARCHAR2(45),
    USER_AGENT VARCHAR2(255),
    FECHA_ACCESO TIMESTAMP NOT NULL,
    CONSTRAINT PK_BITACORA_LECTURA PRIMARY KEY (ID_LECTURA, FECHA_ACCESO)
)
PARTITION BY RANGE (FECHA_ACCESO)
INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_INICIAL VALUES LESS THAN (TO_DATE('2026-01-01', 'YYYY-MM-DD'))
);

CREATE INDEX IDX_LECTURA_PERSONA ON BITACORA_LECTURA(ID_PERSONA) LOCAL;
CREATE INDEX IDX_LECTURA_USUARIO ON BITACORA_LECTURA(USUARIO_LECTOR) LOCAL;

-- =====================================================
-- TABLA: EVENTO_AUDITORIA_DLQ
-- =====================================================
CREATE TABLE EVENTO_AUDITORIA_DLQ (
    ID_FALLO RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    TIPO_EVENTO VARCHAR2(80) NOT NULL,
    PAYLOAD_EVENTO CLOB NOT NULL,
    TIPO_ERROR VARCHAR2(120) NOT NULL,
    MENSAJE_ERROR VARCHAR2(500),
    ESTADO VARCHAR2(30) NOT NULL,
    INTENTOS_REINTENTO NUMBER(5) DEFAULT 0 NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_ULTIMO_INTENTO TIMESTAMP,
    CONSTRAINT CK_DLQ_ESTADO CHECK (ESTADO IN (
        'PENDIENTE_REINTENTO', 'PROCESANDO', 'FALLIDO_DEFINITIVO', 'RESUELTO'))
);

CREATE INDEX IDX_DLQ_ESTADO ON EVENTO_AUDITORIA_DLQ(ESTADO);
CREATE INDEX IDX_DLQ_FECHA ON EVENTO_AUDITORIA_DLQ(FECHA_REGISTRO);

-- =====================================================
-- TABLA: BITACORA_SEGURIDAD
-- =====================================================
CREATE TABLE BITACORA_SEGURIDAD (
    ID_ALERTA RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    USUARIO_AFECTADO VARCHAR2(100),
    TIPO_ANOMALIA VARCHAR2(50) NOT NULL,
    SEVERIDAD VARCHAR2(20) NOT NULL,
    METADATA_CONTEXTO CLOB,
    ESTADO_ALERTA VARCHAR2(30) DEFAULT 'NO_RESUELTA' NOT NULL,
    FECHA_DETECCION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_RESOLUCION TIMESTAMP,
    RESUELTO_POR VARCHAR2(100),
    OBSERVACIONES VARCHAR2(500),
    CONSTRAINT CK_SEGURIDAD_TIPO_ANOMALIA CHECK (TIPO_ANOMALIA IN (
        'IMPOSSIBLE_TRAVEL', 'RATE_LIMIT_EXCEEDED', 'UNAUTHORIZED_ACCESS',
        'BREAK_GLASS_ACCESS', 'PROMPT_INJECTION', 'MASSIVE_DOWNLOAD',
        'OUT_OF_HOURS_MODIFICATION', 'SUSPICIOUS_LOGIN_PATTERN')),
    CONSTRAINT CK_SEGURIDAD_SEVERIDAD CHECK (SEVERIDAD IN ('INFO', 'WARNING', 'CRITICAL')),
    CONSTRAINT CK_SEGURIDAD_ESTADO CHECK (ESTADO_ALERTA IN (
        'NO_RESUELTA', 'EN_INVESTIGACION', 'RESUELTA', 'FALSO_POSITIVO'))
);

CREATE INDEX IDX_SEGURIDAD_TIPO ON BITACORA_SEGURIDAD(TIPO_ANOMALIA);
CREATE INDEX IDX_SEGURIDAD_FECHA ON BITACORA_SEGURIDAD(FECHA_DETECCION);
CREATE INDEX IDX_SEGURIDAD_ESTADO ON BITACORA_SEGURIDAD(ESTADO_ALERTA);
CREATE INDEX IDX_SEGURIDAD_USUARIO ON BITACORA_SEGURIDAD(USUARIO_AFECTADO);

-- =====================================================
-- TABLA: SESION_USUARIO
