-- Execute as a pre-provisioned SAL_ACTIVITIES schema owner.
-- Logical-model mapping:
-- id_actividad -> ID; nombre -> NAME; descripcion -> DESCRIPTION;
-- fecha_actividad + hora_inicio/hora_fin -> START_AT/END_AT;
-- lugar -> PLACE; estado -> STATE; id_usuario_creador -> CREATOR_USER_ID.

CREATE TABLE SAL_ACTIVITIES.ACTIVITY_PLACE_LOCKS (
    PLACE_KEY VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_SAL_ACT_PLACE_LOCKS PRIMARY KEY (PLACE_KEY)
);

CREATE TABLE SAL_ACTIVITIES.ACTIVITIES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(300 CHAR),
    START_AT TIMESTAMP NOT NULL,
    END_AT TIMESTAMP NOT NULL,
    PLACE VARCHAR2(100 CHAR) NOT NULL,
    PLACE_KEY VARCHAR2(100 CHAR) NOT NULL,
    STATE VARCHAR2(20 CHAR) DEFAULT 'SCHEDULED' NOT NULL,
    CREATOR_USER_ID NUMBER NOT NULL,
    VERSION NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SAL_ACTIVITIES PRIMARY KEY (ID),
    CONSTRAINT CK_SAL_ACTIVITIES_TIME CHECK (END_AT > START_AT),
    CONSTRAINT CK_SAL_ACTIVITIES_STATE CHECK (
        STATE IN ('SCHEDULED', 'IN_PROGRESS', 'FINISHED', 'CANCELLED')
    )
);

CREATE INDEX SAL_ACTIVITIES.IX_ACTIVITIES_OVERLAP
    ON SAL_ACTIVITIES.ACTIVITIES (PLACE_KEY, START_AT, END_AT, STATE);

COMMENT ON COLUMN SAL_ACTIVITIES.ACTIVITIES.START_AT IS
    'Oracle representation of logical fecha_actividad and hora_inicio';
COMMENT ON COLUMN SAL_ACTIVITIES.ACTIVITIES.END_AT IS
    'Oracle representation of logical fecha_actividad and hora_fin';
COMMENT ON COLUMN SAL_ACTIVITIES.ACTIVITIES.CREATOR_USER_ID IS
    'Stable logical id_usuario_creador; Auth FK deferred until its physical owner is agreed';
