-- 11. CREAR VISTA BANDEJA
-- =====================================================
CREATE OR REPLACE VIEW V_BANDEJA_ALERTAS AS
SELECT 
    a.ID_ALERTA,
    p.NOMBRE || ' ' || p.APELLIDO AS NOMBRE_PACIENTE,
    p.AREA_TRABAJO,
    a.NIVEL_SEVERIDAD,
    a.ESTADO,
    a.FECHA_GENERACION,
    a.FECHA_VENCIMIENTO_SLA,
    EXTRACT(HOUR FROM (a.FECHA_VENCIMIENTO_SLA - SYSTIMESTAMP)) AS HORAS_SLA_RESTANTES,
    (SELECT LISTAGG(d.TIPO_INDICADOR, ', ') WITHIN GROUP (ORDER BY d.TIPO_INDICADOR) 
     FROM ALERTA_CLINICA_DETALLE d 
     WHERE d.ID_ALERTA = a.ID_ALERTA) AS INDICADORES_AFECTADOS,
    CASE 
        WHEN a.FECHA_VENCIMIENTO_SLA < SYSTIMESTAMP AND a.ESTADO IN ('PENDIENTE', 'EN_REVISION') 
        THEN 'VENCIDO' 
        ELSE 'ACTIVO' 
    END AS ESTADO_SLA
FROM ALERTA_CLINICA a
INNER JOIN PERSONA p ON a.ID_PERSONA = p.ID_PERSONA;

-- =====================================================
-- 12. CREAR TRIGGERS
-- =====================================================
CREATE OR REPLACE TRIGGER TRG_ALERTA_SLA
BEFORE INSERT ON ALERTA_CLINICA
FOR EACH ROW
BEGIN
    IF :NEW.NIVEL_SEVERIDAD = 'CRITICO' THEN
        :NEW.FECHA_VENCIMIENTO_SLA := SYSTIMESTAMP + INTERVAL '72' HOUR;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_ALERTA_AUDITORIA
BEFORE UPDATE ON ALERTA_CLINICA
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO != :NEW.ESTADO THEN
        INSERT INTO AUDITORIA_ALERTA (ID_ALERTA, CAMPO_MODIFICADO, VALOR_ANTERIOR, VALOR_NUEVO, ACCION)
        VALUES (:NEW.ID_ALERTA, 'ESTADO', :OLD.ESTADO, :NEW.ESTADO, 'CAMBIAR_ESTADO');
    END IF;
END;
/

