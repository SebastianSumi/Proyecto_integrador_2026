CREATE INDEX IDX_SESION_USUARIO_FECHA ON SESION_USUARIO(USUARIO, FECHA_LOGIN);
CREATE INDEX IDX_SESION_IP ON SESION_USUARIO(DIRECCION_IP);

-- =====================================================
-- TABLA: MANIFIESTO_ARCHIVADO_FRIO
-- =====================================================
CREATE TABLE MANIFIESTO_ARCHIVADO_FRIO (
    ID_MANIFIESTO RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    RANGO_FECHA_INICIO TIMESTAMP NOT NULL,
    RANGO_FECHA_FIN TIMESTAMP NOT NULL,
    TOTAL_REGISTROS_EXPORTADOS NUMBER(12) NOT NULL,
    RUTA_COLD_STORAGE VARCHAR2(300) NOT NULL,
    TAMANO_ARCHIVO_BYTES NUMBER(19) NOT NULL,
    HASH_MANIFIESTO VARCHAR2(64) NOT NULL,
    FIRMA_RSA VARCHAR2(1000),
    FECHA_EXPORTACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESPONSABLE_PURGA VARCHAR2(100) NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'GENERADO' NOT NULL,
    FECHA_PURGA TIMESTAMP,
    CONSTRAINT CK_MANIFIESTO_ESTADO CHECK (ESTADO IN ('GENERADO', 'ARCHIVADO', 'PURGADO'))
);

CREATE INDEX IDX_MANIFIESTO_ESTADO ON MANIFIESTO_ARCHIVADO_FRIO(ESTADO);
CREATE INDEX IDX_MANIFIESTO_RANGO ON MANIFIESTO_ARCHIVADO_FRIO(RANGO_FECHA_INICIO, RANGO_FECHA_FIN);

-- =====================================================
-- TABLA: PARTICION_BITACORA
-- =====================================================
CREATE TABLE PARTICION_BITACORA (
    ID_PARTICION RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NOMBRE_PARTICION VARCHAR2(100) NOT NULL UNIQUE,
    TABLA_ORIGEN VARCHAR2(60) NOT NULL,
    RANGO_FECHA_INICIO TIMESTAMP NOT NULL,
    RANGO_FECHA_FIN TIMESTAMP NOT NULL,
    TOTAL_REGISTROS NUMBER(12),
    TAMANO_BYTES NUMBER(19),
    ESTADO VARCHAR2(30) DEFAULT 'ACTIVA' NOT NULL,
    ARCHIVADA VARCHAR2(1) DEFAULT 'N',
    PURGADA VARCHAR2(1) DEFAULT 'N',
    ID_MANIFIESTO RAW(16),
    FECHA_CREACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_PARTICION_ARCHIVADA CHECK (ARCHIVADA IN ('S', 'N')),
    CONSTRAINT CK_PARTICION_PURGADA CHECK (PURGADA IN ('S', 'N')),
    CONSTRAINT FK_PARTICION_MANIFIESTO FOREIGN KEY (ID_MANIFIESTO)
        REFERENCES MANIFIESTO_ARCHIVADO_FRIO(ID_MANIFIESTO)
);

CREATE INDEX IDX_PARTICION_TABLA ON PARTICION_BITACORA(TABLA_ORIGEN);
CREATE INDEX IDX_PARTICION_ARCHIVADA ON PARTICION_BITACORA(ARCHIVADA);
CREATE INDEX IDX_PARTICION_PURGADA ON PARTICION_BITACORA(PURGADA);

