-- =====================================================
-- TRIGGER WORM: prohibe UPDATE y DELETE en bitacora
-- =====================================================
CREATE OR REPLACE TRIGGER TRG_BITACORA_WORM
BEFORE UPDATE OR DELETE ON BITACORA_TRANSACCIONAL
FOR EACH ROW
BEGIN
    RAISE_APPLICATION_ERROR(-20001,
        'BITACORA_TRANSACCIONAL es WORM (Write Once Read Many). No se permite UPDATE ni DELETE.');
END;
/

