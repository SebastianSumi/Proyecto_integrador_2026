-- Execute as SAL_ACTIVITIES after 05_create_activities.sql.
-- Enrollment belongs to Activities and stores the current/latest membership state.

CREATE TABLE SAL_ACTIVITIES.ACTIVITY_ENROLLMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ACTIVITY_ID NUMBER NOT NULL,
    PERSON_ID NUMBER NOT NULL,
    STATE VARCHAR2(20 CHAR) DEFAULT 'ENROLLED' NOT NULL,
    ENROLLED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CANCELLED_AT TIMESTAMP,
    CONSTRAINT PK_ACTIVITY_ENROLLMENTS PRIMARY KEY (ID),
    CONSTRAINT FK_ENROLLMENT_ACTIVITY FOREIGN KEY (ACTIVITY_ID)
        REFERENCES SAL_ACTIVITIES.ACTIVITIES (ID),
    CONSTRAINT UK_ACTIVITY_ENROLLMENT_PERSON UNIQUE (ACTIVITY_ID, PERSON_ID),
    CONSTRAINT CK_ACTIVITY_ENROLLMENT_STATE CHECK (STATE IN ('ENROLLED', 'CANCELLED')),
    CONSTRAINT CK_ACTIVITY_ENROLLMENT_DATES CHECK (
        (STATE = 'ENROLLED' AND CANCELLED_AT IS NULL)
        OR (STATE = 'CANCELLED' AND CANCELLED_AT IS NOT NULL)
    )
);

CREATE INDEX SAL_ACTIVITIES.IX_ENROLLMENT_ACTIVITY_STATE
    ON SAL_ACTIVITIES.ACTIVITY_ENROLLMENTS (ACTIVITY_ID, STATE);

CREATE INDEX SAL_ACTIVITIES.IX_ENROLLMENT_PERSON_STATE
    ON SAL_ACTIVITIES.ACTIVITY_ENROLLMENTS (PERSON_ID, STATE);

COMMENT ON COLUMN SAL_ACTIVITIES.ACTIVITY_ENROLLMENTS.PERSON_ID IS
    'Stable logical id_persona; Personal FK deferred until its physical owner is agreed';
